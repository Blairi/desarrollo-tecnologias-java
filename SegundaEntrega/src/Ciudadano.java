public class Ciudadano {
    private String nombre;
    private String razonSocial;
    private String domicilio;
    private String RFC;
    private String CURP;
    private String apoderadoLegal;
    private String cumpleanios;

    public Ciudadano() {
    }

    public String getNombre() {
        return nombre;
    }

    public void setNombre(String nombre) {
        this.nombre = nombre;
    }

    public String getRazonSocial() {
        return razonSocial;
    }

    public void setRazonSocial(String razonSocial) {
        this.razonSocial = razonSocial;
    }

    public String getDomicilio() {
        return domicilio;
    }

    public void setDomicilio(String domicilio) {
        this.domicilio = domicilio;
    }

    public String getRFC() {
        return RFC;
    }

    public void setRFC(String RFC) {
        this.RFC = RFC;
    }

    public String getCURP() {
        return CURP;
    }

    public void setCURP(String CURP) {
        this.CURP = CURP;
    }

    public String getApoderadoLegal() {
        return apoderadoLegal;
    }

    public void setApoderadoLegal(String apoderadoLegal) {
        this.apoderadoLegal = apoderadoLegal;
    }

    public String getCumpleanios() {
        return cumpleanios;
    }

    public void setCumpleanios(String cumpleanios) {
        this.cumpleanios = cumpleanios;
    }
}
